import fs from 'node:fs';
import path from 'node:path';
import type { Entry } from '@hub/contracts';

type Source = {
  key: string;
  kind: 'github' | 'n8n_official';
  repo?: string;
  expectedLicence: string | null;
  status: 'active' | 'excluded';
};

// The public tree's attribution rows are acquisition counts over a different corpus snapshot
// (docs/audits/2026-10-19-production-readiness/05-baseline-independent-review.md:104,137). They are
// stated once, separately, and never added to this register's canonical totals.
const PUBLIC_ACQUISITION_ENTRIES = 13_221;
const formatCount = (value: number): string => value.toLocaleString('en-US');

function sourceUrl(source: Source): string {
  return source.kind === 'n8n_official'
    ? 'https://n8n.io/workflows/'
    : `https://github.com/${source.repo}`;
}

function countEntries(source: Source, entries: Entry[]): number {
  return entries.filter((entry) =>
    source.kind === 'n8n_official'
      ? entry.source?.kind === 'n8n_official'
      : entry.source?.repo === source.repo,
  ).length;
}

function sourceRow(source: Source, entries: Entry[]): string {
  const name = source.kind === 'n8n_official' ? 'Official n8n templates' : source.repo!;
  const licence = source.expectedLicence ?? 'No asserted licence';
  return `| [${name}](${sourceUrl(source)}) | ${licence} | ${countEntries(source, entries)} |`;
}

export function renderAttributions(sources: Source[], entries: Entry[]): string {
  const active = sources.filter((source) => source.status === 'active');
  const excluded = sources.filter((source) => source.status === 'excluded' && countEntries(source, entries) > 0);
  const activeTotal = active.reduce((sum, source) => sum + countEntries(source, entries), 0);
  const excludedTotal = excluded.reduce((sum, source) => sum + countEntries(source, entries), 0);
  const total = activeTotal + excludedTotal;

  return [
    '# Attributions',
    '',
    '> Generated by `npm run attributions`; do not edit by hand.',
    '',
    'This register covers the source configuration used for the currently packaged canonical catalogue. Entry-level rights remain authoritative: official and other link-only entries are not redistributed as workflow JSON.',
    '',
    '| Source | Declared licence | Canonical entries |',
    '| --- | --- | ---: |',
    ...active.map((source) => sourceRow(source, entries)),
    '',
    '## Excluded sources with retained credit',
    '',
    'These sources are excluded from acquisition, but entries acquired while they were configured are still catalogued and keep their upstream credit.',
    '',
    '| Source | Declared licence | Canonical entries |',
    '| --- | --- | ---: |',
    ...(excluded.length === 0 ? ['| — | — | 0 |'] : excluded.map((source) => sourceRow(source, entries))),
    '',
    `Active-source canonical entries: ${formatCount(activeTotal)}. Excluded-source canonical entries with retained credit: ${formatCount(excludedTotal)}. Total canonical entries: ${formatCount(total)}.`,
    '',
    `Public-tree acquisition entries: ${formatCount(PUBLIC_ACQUISITION_ENTRIES)}. This is an acquisition count with a different basis; it is not summed with the canonical total.`,
    '',
    '## Licence authority',
    '',
    'The binding authority for this repository is **MIT** for application and scanner code (`LICENSE`) and **Personal / Non-Commercial** for the aggregated workflow catalogue dataset (`docs/LICENSING.md`). That is the existing grant; this register does not relicense anything.',
    '',
    'The public tree still carries a stale **CC BY-SA 4.0** header for derived catalogue metadata (`docs/REPOSITORY-MODEL.md` there). That is an unresolved, public-only extraction defect to correct as a documentation fix in the public extraction PR; it is not a second grant. Upstream entry-level rights remain authoritative and are not inferred from either statement.',
    '',
  ].join('\n');
}

function readEntries(dataDir: string): Entry[] {
  return fs.readdirSync(dataDir)
    .filter((file) => /^catalogue-\d+\.json$/.test(file))
    .sort()
    .flatMap((file) => JSON.parse(fs.readFileSync(path.join(dataDir, file), 'utf8')) as Entry[]);
}

function main(): void {
  const root = process.cwd();
  const sources = JSON.parse(fs.readFileSync(path.join(root, 'pipeline', 'sources.json'), 'utf8')) as Source[];
  const output = renderAttributions(sources, readEntries(path.join(root, 'data')));
  const outputPath = path.join(root, 'ATTRIBUTIONS.md');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== output) {
      throw new Error('ATTRIBUTIONS.md is out of date; run npm run attributions');
    }
    return;
  }
  fs.writeFileSync(outputPath, output, 'utf8');
}

if (process.argv[1]?.endsWith('generate-attributions.ts')) main();
