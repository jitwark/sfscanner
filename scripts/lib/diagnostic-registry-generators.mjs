import { CATEGORIES, DIAGNOSTIC_REGISTRY_VERSION, EFFECT_MODES, literal, PROJECTIONS } from './diagnostic-registry.mjs';

/**
 * The artifacts projected from the registry table. Rendering is deterministic and pure: the
 * same model always produces byte-identical text, which is what makes the committed artifacts
 * checkable (`npm run check:diagnostic-registry`) instead of trusted.
 */
export const CORE_ARTIFACT = 'packages/scanner-core/src/diagnostics/registry.ts';
export const CONTRACTS_ARTIFACT = 'contracts/scanner-v2-diagnostics.generated.ts';

const CODES_PER_LINE = 3;

function header(model, extra = []) {
  return [
    '// Generated by scripts/generate-diagnostic-registry.mjs; DO NOT EDIT.',
    `// diagnostic-registry:version=${DIAGNOSTIC_REGISTRY_VERSION}`,
    `// diagnostic-registry:source=${model.source}`,
    `// diagnostic-registry:rows=${model.rows.length}`,
    `// diagnostic-registry:digest=${model.digest}`,
    ...extra,
    '',
  ];
}

function codeUnion(model) {
  const lines = [];
  for (let index = 0; index < model.rows.length; index += CODES_PER_LINE) {
    lines.push(`  | ${model.rows.slice(index, index + CODES_PER_LINE).map((row) => literal(row.code)).join(' | ')}`);
  }
  return lines.join('\n');
}

function coreRows(model) {
  return model.rows.map((row) => `  row(${literal(row.code)}, ${literal(row.category)}, ${literal(row.aggregateEffect)}, ${literal(row.assessmentEligible)}, ${row.v1Code === null ? 'null' : literal(row.v1Code)}, ${literal(row.v1Projection)}),`);
}

const domainRecord = (values) => `Object.freeze({ ${values.map((value) => `${literal(value)}: true`).join(', ')} })`;

function renderCore(model) {
  return `${header(model, [
    '// Regenerate with `npm run generate:diagnostic-registry` after editing the registry table.',
    '// Every code, category, effect mode, assessment mode, and v1 projection below is projected from it.',
  ]).join('\n')}import type { SourceMemberRefV2 } from '../source/source-types';

export type DiagnosticCategoryV2 = ${CATEGORIES.map(literal).join(' | ')};
export type DiagnosticAggregateEffectV2 = 'NONE' | 'DEGRADED' | 'INDETERMINATE';
export type DiagnosticAggregateEffectModeV2 = DiagnosticAggregateEffectV2 | 'BY_CAPABILITY';
export type DiagnosticAssessmentEligibilityModeV2 = boolean | 'BY_CAPABILITY';
export type DiagnosticV1ProjectionV2 = ${PROJECTIONS.map(literal).join(' | ')};

export type DiagnosticCodeV2 =
${codeUnion(model)};

export type AnalysisDiagnosticV2 = Readonly<{
  id: string;
  code: DiagnosticCodeV2;
  category: DiagnosticCategoryV2;
  capabilityId: string;
  aggregateEffect: DiagnosticAggregateEffectV2;
  assessmentEligible: boolean;
  location?: SourceMemberRefV2;
  observed?: number;
  maximum?: number;
  omitted?: number;
}>;

export type DiagnosticRegistryEntryV2 = Readonly<{
  code: DiagnosticCodeV2;
  category: DiagnosticCategoryV2;
  aggregateEffect: DiagnosticAggregateEffectModeV2;
  assessmentEligible: DiagnosticAssessmentEligibilityModeV2;
  v1Code: string | null;
  v1Projection: DiagnosticV1ProjectionV2;
}>;

const row = (
  code: DiagnosticCodeV2,
  category: DiagnosticCategoryV2,
  aggregateEffect: DiagnosticAggregateEffectModeV2,
  assessmentEligible: DiagnosticAssessmentEligibilityModeV2,
  v1Code: string | null,
  v1Projection: DiagnosticV1ProjectionV2,
): DiagnosticRegistryEntryV2 => Object.freeze({
  code, category, aggregateEffect, assessmentEligible, v1Code, v1Projection,
});

export const DIAGNOSTIC_REGISTRY: readonly DiagnosticRegistryEntryV2[] = Object.freeze([
${coreRows(model).join('\n')}
]);

export const DIAGNOSTIC_CODES_V2: readonly DiagnosticCodeV2[] = Object.freeze(
  DIAGNOSTIC_REGISTRY.map((entry) => entry.code),
);

const categorySet: Readonly<Record<DiagnosticCategoryV2, true>> = ${domainRecord(CATEGORIES)};
const effectSet: Readonly<Record<DiagnosticAggregateEffectModeV2, true>> = ${domainRecord(['NONE', ...EFFECT_MODES])};
const projectionSet: Readonly<Record<DiagnosticV1ProjectionV2, true>> = ${domainRecord(PROJECTIONS)};
const byCode = new Map<string, DiagnosticRegistryEntryV2>(DIAGNOSTIC_REGISTRY.map((entry) => [entry.code, entry]));

if (DIAGNOSTIC_REGISTRY.length !== ${model.rows.length} || byCode.size !== DIAGNOSTIC_REGISTRY.length) throw new TypeError('Invalid diagnostic registry');
for (const entry of DIAGNOSTIC_REGISTRY) {
  if (categorySet[entry.category] !== true || effectSet[entry.aggregateEffect] !== true || projectionSet[entry.v1Projection] !== true) {
    throw new TypeError('Invalid diagnostic registry');
  }
  if (entry.assessmentEligible !== 'BY_CAPABILITY' && typeof entry.assessmentEligible !== 'boolean') {
    throw new TypeError('Invalid diagnostic registry');
  }
}

/**
 * The status mapping (aggregate effect) and the assessment mapping. A \`BY_CAPABILITY\`
 * row is resolved by the owning capability's registry-fixed requiredness: required loss
 * is \`INDETERMINATE\`/ineligible, optional or report-only loss is \`DEGRADED\`/eligible.
 */
export function classifyDiagnostic(code: DiagnosticCodeV2, capabilityRequiredness?: boolean): Readonly<{
  category: DiagnosticCategoryV2;
  aggregateEffect: DiagnosticAggregateEffectV2;
  assessmentEligible: boolean;
}> {
  const entry = byCode.get(code);
  if (!entry) throw new TypeError('Unknown diagnostic code');
  if (entry.aggregateEffect === 'BY_CAPABILITY' && typeof capabilityRequiredness !== 'boolean') {
    throw new TypeError('Diagnostic capability requiredness is not fixed');
  }
  const required = entry.aggregateEffect === 'BY_CAPABILITY' && capabilityRequiredness === true;
  return Object.freeze({
    category: entry.category,
    aggregateEffect: entry.aggregateEffect === 'BY_CAPABILITY' ? (required ? 'INDETERMINATE' : 'DEGRADED') : entry.aggregateEffect,
    assessmentEligible: entry.assessmentEligible === 'BY_CAPABILITY' ? !required : entry.assessmentEligible,
  });
}
`;
}

function contractsRows(model) {
  return model.rows.map((row) => `  ${row.code}: [${literal(row.category)}, ${literal(row.aggregateEffect)}, ${literal(row.assessmentEligible)}],`);
}

function renderContracts(model) {
  const byCapability = model.rows.filter((row) => row.aggregateEffect === 'BY_CAPABILITY');
  return `${header(model, [
    '// Regenerate with `npm run generate:diagnostic-registry` after editing the registry table.',
    '// The result validator reads this instead of keeping its own copy of the vocabulary.',
  ]).join('\n')}export type DiagnosticCodeV2 =
${codeUnion(model)};

export type DiagnosticCategoryV2 = ${CATEGORIES.map(literal).join(' | ')};
export type DiagnosticAggregateEffectModeV2 = ${EFFECT_MODES.map(literal).join(' | ')};
export type DiagnosticAssessmentEligibilityModeV2 = boolean | 'BY_CAPABILITY';

/** [category, aggregate effect, assessment eligibility], one entry per registered code. */
export const DIAGNOSTIC_REGISTRY_V2: Readonly<Record<DiagnosticCodeV2, readonly [DiagnosticCategoryV2, DiagnosticAggregateEffectModeV2, DiagnosticAssessmentEligibilityModeV2]>> = Object.freeze({
${contractsRows(model).join('\n')}
});

/** The codes whose effect and eligibility the owning capability's requiredness decides. */
export const BY_CAPABILITY_DIAGNOSTIC_CODES_V2: Readonly<Partial<Record<DiagnosticCodeV2, true>>> = Object.freeze({
${byCapability.map((row) => `  ${literal(row.code)}: true,`).join('\n')}
});
`;
}

export function renderDiagnosticRegistryArtifacts(model) {
  return Object.freeze({ [CORE_ARTIFACT]: renderCore(model), [CONTRACTS_ARTIFACT]: renderContracts(model) });
}
